import assert from "node:assert/strict";
import fs from "node:fs";
import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const outDir = mkdtempSync(path.join(tmpdir(), "ronic-market-test-"));

// Mock localStorage for Node environment before module import
const storage = new Map();
globalThis.localStorage = {
  getItem: (k) => storage.get(k) ?? null,
  setItem: (k, v) => storage.set(k, String(v)),
  removeItem: (k) => storage.delete(k),
  clear: () => storage.clear(),
};
globalThis.window = globalThis;

const compile = spawnSync(
  process.execPath,
  [
    path.join(root, "node_modules", "typescript", "bin", "tsc"),
    "--target", "ES2022",
    "--module", "ES2022",
    "--moduleResolution", "bundler",
    "--lib", "ES2022,DOM",
    "--strict",
    "--skipLibCheck",
    path.join(root, "src", "kernel", "marketplaceCatalog.ts"),
    "--outDir", outDir,
  ],
  { encoding: "utf8" }
);
assert.equal(compile.status, 0, compile.stdout + compile.stderr);

const targetFile = fs.readdirSync(outDir, { recursive: true }).find((f) => f.endsWith("marketplaceCatalog.js"));
if (!targetFile) throw new Error("marketplaceCatalog.js not generated by tsc: " + compile.stderr);

const mod = await import(pathToFileURL(path.join(outDir, targetFile)).href);
process.on("exit", () => rmSync(outDir, { recursive: true, force: true }));

const {
  MARKETPLACE_CATALOG,
  isItemInstalled,
  isItemConnected,
  getItemStatus,
  getMcpAuthVault,
  getAuthenticatedMcpIds,
  saveMcpAuthRecord,
  removeMcpAuthRecord,
} = mod;

test("Marketplace Catalog has proper authentication method mapping for all items", () => {
  assert.ok(MARKETPLACE_CATALOG && MARKETPLACE_CATALOG.length >= 50, "Catalog should have at least 50 items");

  // Check Google Docs (OAuth)
  const gdocs = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-google-docs");
  assert.ok(gdocs, "Google Docs should exist");
  assert.equal(gdocs.authConfig?.method, "oauth", "Google Docs should use OAuth");
  assert.equal(gdocs.requiresAuth, true, "Google Docs requires auth");

  // Check Shopify (Multi-field)
  const shopify = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-shopify");
  assert.ok(shopify, "Shopify should exist");
  assert.equal(shopify.authConfig?.method, "multi_field", "Shopify should use multi_field");
  assert.ok(shopify.authConfig?.fields?.length >= 2, "Shopify should require domain and access token");

  // Check Firecrawl (API Key)
  const firecrawl = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-firecrawl");
  assert.ok(firecrawl, "Firecrawl should exist");
  assert.equal(firecrawl.authConfig?.method, "api_key", "Firecrawl should use api_key");

  // Check Docker (Local Daemon)
  const docker = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-docker");
  assert.ok(docker, "Docker should exist");
  assert.equal(docker.authConfig?.method, "local_daemon", "Docker should use local_daemon");
  assert.equal(docker.requiresAuth, false, "Docker does not require external key");

  // Check Memory (Zero Auth)
  const memory = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-memory");
  assert.ok(memory, "Memory should exist");
  assert.equal(memory.authConfig?.method, "none", "Memory should have none");
  assert.equal(memory.requiresAuth, false, "Memory does not require auth");
});

test("isItemConnected never returns true for unauthenticated services", () => {
  storage.clear();

  const dummySnap = {
    mcpServers: [
      { id: "mcp-notion", name: "Notion", transport: "sse", command: "", args: [], url: "https://mcp.notion.com/mcp", trust: "trusted", declaredTools: [], enables: [], lastError: "" },
      { id: "mcp-shopify", name: "Shopify Merchant", transport: "sse", command: "", args: [], url: "https://mcp.shopify.com/mcp", trust: "trusted", declaredTools: [], enables: [], lastError: "" },
    ],
    plugins: [],
    skills: [],
  };

  const notion = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-notion");
  const shopify = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-shopify");

  // Even though they are installed in snap.mcpServers, they lack auth records!
  assert.equal(isItemConnected(notion, dummySnap), false, "Notion should not show connected without authentication");
  assert.equal(isItemConnected(shopify, dummySnap), false, "Shopify should not show connected without credentials");
  assert.equal(getItemStatus(notion, dummySnap), "needs_auth", "Notion should have status needs_auth");
  assert.equal(getItemStatus(shopify, dummySnap), "needs_auth", "Shopify should have status needs_auth");

  // Now authenticate Notion
  saveMcpAuthRecord({
    id: "mcp-notion",
    authMethod: "oauth",
    authenticatedAt: Date.now(),
    accountIdentity: "user@workspace.notion.site",
    credentialMask: "oauth_xyz",
  });

  assert.equal(isItemConnected(notion, dummySnap), true, "Notion should now be connected");
  assert.equal(getItemStatus(notion, dummySnap), "connected", "Notion should now have status connected");
  // Shopify still not authenticated
  assert.equal(isItemConnected(shopify, dummySnap), false, "Shopify remains unauthenticated");
});

test("placeholder identities and a legacy id list do not count as connected", () => {
  storage.clear();
  const dummySnap = {
    mcpServers: [
      { id: "mcp-google-docs", name: "Google Docs", transport: "sse", command: "", args: [], url: "https://mcp.google.com/docs/mcp", trust: "trusted", declaredTools: [], enables: [], lastError: "" },
      { id: "mcp-shopify", name: "Shopify Merchant", transport: "sse", command: "", args: [], url: "https://mcp.shopify.com/mcp", trust: "trusted", declaredTools: [], enables: [], lastError: "" },
      { id: "mcp-docker", name: "Docker", transport: "stdio", command: "docker", args: ["version"], url: "", trust: "trusted", declaredTools: [], enables: [], lastError: "" },
    ],
    plugins: [],
    skills: [],
  };
  const gdocs = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-google-docs");
  const shopify = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-shopify");
  const docker = MARKETPLACE_CATALOG.find((i) => i.id === "mcp-docker");

  localStorage.setItem("ronic_mcp_authenticated_ids", JSON.stringify(["mcp-shopify", "mcp-google-docs"]));
  assert.equal(isItemConnected(shopify, dummySnap), false, "A leftover id without a vault record is not connected");
  assert.equal(getAuthenticatedMcpIds().has("mcp-shopify"), false);

  saveMcpAuthRecord({
    id: "mcp-google-docs",
    authMethod: "oauth",
    authenticatedAt: Date.now(),
    accountIdentity: "user@googleworkspace.com",
    credentialMask: "oaut...cmvg",
  });
  assert.equal(isItemConnected(gdocs, dummySnap), false, "The placeholder Google identity is not a session");
  assert.equal(getMcpAuthVault()["mcp-google-docs"], undefined);

  saveMcpAuthRecord({
    id: "mcp-docker",
    authMethod: "local_daemon",
    authenticatedAt: Date.now(),
    accountIdentity: "Local Machine",
    credentialMask: "configured",
  });
  assert.equal(isItemConnected(docker, dummySnap), false, "Docker stays disconnected until a version probe sets verified");
});
