import { jsPDF } from "jspdf";
import fs from "fs";
import path from "path";
import os from "os";

const doc = new jsPDF({
  orientation: "portrait",
  unit: "mm",
  format: "a4"
});

const pageWidth = doc.internal.pageSize.getWidth();
const pageHeight = doc.internal.pageSize.getHeight();
const margin = 18;
const contentWidth = pageWidth - margin * 2;
let y = margin;

function checkPage(needHeight = 10) {
  if (y + needHeight > pageHeight - margin) {
    doc.addPage();
    y = margin;
  }
}

// Header
doc.setFillColor(24, 24, 27);
doc.rect(margin, y, contentWidth, 24, "F");
doc.setTextColor(255, 255, 255);
doc.setFontSize(16);
doc.setFont("helvetica", "bold");
doc.text("Sales & Marketing Funnel Automation", margin + 6, y + 10);
doc.setFontSize(10);
doc.setFont("helvetica", "normal");
doc.setTextColor(200, 200, 200);
doc.text("Workflow ID: sales-marketing-funnel-001  |  Version 1.0.0  |  Status: Ready", margin + 6, y + 18);
y += 32;

// Overview
doc.setTextColor(20, 20, 20);
doc.setFontSize(13);
doc.setFont("helvetica", "bold");
doc.text("Executive Summary", margin, y);
y += 6;

doc.setFontSize(10);
doc.setFont("helvetica", "normal");
doc.setTextColor(60, 60, 60);
const summaryText = "This automated workflow implements an end-to-end sales and marketing funnel spanning lead capture via browser automation, AI-driven lead qualification, multi-tier nurture and Calendly booking sequences, and automated 7-day post-purchase customer retention.";
const summaryLines = doc.splitTextToSize(summaryText, contentWidth);
doc.text(summaryLines, margin, y);
y += summaryLines.length * 5 + 6;

// Node Definitions
const nodes = [
  {
    step: "Node 1",
    name: "Lead Capture",
    type: "Browser Automation",
    trigger: "on_form_submission + on_ad_click",
    desc: "Monitors lead generation pages (https://ronic-os.example.com/leads). Captures incoming submissions from #lead-form and ad click triggers (.ad-cta-button). Extracts email, name, job title, company size, UTM attribution (source, medium, campaign, referrer), and records data into CRM.",
    outputs: "lead_id, email, company, captured_at",
    next: "lead-qualification"
  },
  {
    step: "Node 2",
    name: "Lead Qualification",
    type: "LLM Reasoning",
    trigger: "on_lead_captured",
    desc: "Autonomous LLM reasoning engine assesses incoming lead profile against company criteria. Applies scoring heuristics: Hot (score >= 80), Warm (score 50-79), and Cold (score < 50). Updates lead tier and qualification timestamp in CRM.",
    outputs: "lead_id, score, tier",
    next: "nurture-conversion"
  },
  {
    step: "Node 3",
    name: "Nurture & Conversion",
    type: "Bot Action & Integration",
    trigger: "on_lead_qualified",
    desc: "Dispatches automated multi-channel sequences based on lead tier via SendGrid: Hot leads receive immediate demo invitation followed by 24h follow-up and automated Calendly 30min booking. Warm leads receive welcome email, Day 3 case study, and Day 7 soft CTA. Cold leads receive bi-weekly updates. Tracks purchase completed conversion events.",
    outputs: "lead_id, tier, emails_sent, demo_booked, purchased_at",
    next: "retention"
  },
  {
    step: "Node 4",
    name: "Retention & Customer Success",
    type: "LLM Reasoning + Bot Action",
    trigger: "on_purchase + 7_days_post_purchase",
    desc: "Automated customer retention engine activates 7 days post-purchase. Analyzes customer usage telemetry, subscription plan, and ARR. Generates personalized onboarding action checklists and relevant upsell recommendations. Automatically alerts Customer Success Managers via Slack if churn risk is elevated.",
    outputs: "onboarding_tasks, upsell_offer, churn_risk_score",
    next: "Completed"
  }
];

nodes.forEach((n) => {
  checkPage(42);
  doc.setFillColor(245, 247, 250);
  doc.roundedRect(margin, y, contentWidth, 38, 2, 2, "F");
  
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(11);
  doc.setFont("helvetica", "bold");
  doc.text(`${n.step}: ${n.name}  [${n.type}]`, margin + 4, y + 7);

  doc.setFontSize(8.5);
  doc.setFont("helvetica", "italic");
  doc.setTextColor(100, 116, 139);
  doc.text(`Trigger: ${n.trigger}  |  Next: ${n.next}`, margin + 4, y + 13);

  doc.setFontSize(8.5);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(51, 65, 85);
  const descLines = doc.splitTextToSize(n.desc, contentWidth - 8);
  doc.text(descLines, margin + 4, y + 19);

  doc.setFontSize(8);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(71, 85, 105);
  doc.text(`Outputs: ${n.outputs}`, margin + 4, y + 34);

  y += 42;
});

// Footer metadata
checkPage(20);
doc.setDrawColor(226, 232, 240);
doc.line(margin, y, margin + contentWidth, y);
y += 6;
doc.setFontSize(8.5);
doc.setFont("helvetica", "normal");
doc.setTextColor(148, 163, 184);
doc.text(`Generated by Omni Workspace OS | Registered in Workflows Engine | ${new Date().toLocaleDateString()}`, margin, y);

// Output to workspace and Downloads
const wsPath = path.resolve("./workflows/sales-marketing-funnel.pdf");
const userDownloads = path.join(os.homedir(), "Downloads", "sales-marketing-funnel.pdf");

const pdfBytes = doc.output("arraybuffer");
fs.writeFileSync(wsPath, Buffer.from(pdfBytes));
fs.writeFileSync(userDownloads, Buffer.from(pdfBytes));

console.log("PDF generated successfully at:");
console.log(" - Workspace:", wsPath);
console.log(" - Downloads:", userDownloads);

